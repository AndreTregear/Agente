/**
 * WHO Child Growth Standards — LMS Reference Data
 *
 * Contains embedded WHO reference tables for the LMS (Lambda-Mu-Sigma) method.
 * Data covers children 0–60 months, both boys and girls.
 *
 * The LMS method uses three parameters at each age:
 *   L (Lambda) — Box-Cox power for skewness
 *   M (Mu)     — Median
 *   S (Sigma)  — Coefficient of variation
 *
 * Source: WHO Multicentre Growth Reference Study Group (2006).
 */

export interface LMSEntry {
  /** Age in months (for age-based indicators) or height in cm (for weight-for-height) */
  x: number;
  L: number;
  M: number;
  S: number;
}

export interface WHOIndicator {
  boys: LMSEntry[];
  girls: LMSEntry[];
}

